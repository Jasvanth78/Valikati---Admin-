import React from 'react';
import { afterEach, expect, test, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import axios from 'axios';
import { CalendarHighlightsEditor } from '../src/components/CalendarHighlightsEditor';
vi.mock('axios', () => ({ default: { put: vi.fn() } }));
afterEach(() => { cleanup(); vi.clearAllMocks(); });
test('admin can publish Tamil-only cards for automatic English translation', async () => {
  vi.mocked(axios.put).mockResolvedValue({ data: {} });
  const onSaved = vi.fn();
  render(<CalendarHighlightsEditor raw="" onSaved={onSaved} />);
  const user = userEvent.setup();
  fireEvent.change(screen.getByLabelText('Date'), { target: { value: '2026-10-20' } });
  await user.click(screen.getByRole('button', { name: 'Add highlight card' }));
  await user.type(screen.getByLabelText('Tamil title'), 'சிறப்பு நாள்');
  await user.click(screen.getByRole('button', { name: 'Publish calendar highlights' }));
  await waitFor(() => expect(onSaved).toHaveBeenCalledOnce());
  expect(JSON.parse((vi.mocked(axios.put).mock.calls[0][1] as any).en)[0].cards[0].titleEn).toBe('');
});
test('admin creates dated bilingual highlights and restores automatic cards', async () => {
  vi.mocked(axios.put).mockResolvedValue({ data: {} });
  const onSaved = vi.fn();
  render(<CalendarHighlightsEditor raw="" onSaved={onSaved} />);
  const user = userEvent.setup();
  fireEvent.change(screen.getByLabelText('Date'), { target: { value: '2026-10-20' } });
  await user.click(screen.getByRole('button', { name: 'Add highlight card' }));
  await user.type(screen.getByLabelText('Tamil title'), 'சிறப்பு');
  await user.type(screen.getByLabelText('English title'), 'Special day');
  await user.type(screen.getByLabelText('English description'), 'Details');
  await user.click(screen.getByRole('button', { name: 'Publish calendar highlights' }));
  await waitFor(() => expect(onSaved).toHaveBeenCalledOnce());
  const body = vi.mocked(axios.put).mock.calls[0][1] as any;
  expect(body.key).toBe('calendar_highlights');
  expect(body.ta).toBe(body.en);
  expect(JSON.parse(body.en)).toEqual([{ date: '2026-10-20', cards: [{ titleTa: 'சிறப்பு', titleEn: 'Special day', descriptionTa: '', descriptionEn: 'Details' }] }]);
  await user.click(screen.getByRole('button', { name: 'Restore automatic highlights' }));
  await user.click(screen.getByRole('button', { name: 'Publish calendar highlights' }));
  await waitFor(() => expect(axios.put).toHaveBeenCalledTimes(2));
  expect(JSON.parse((vi.mocked(axios.put).mock.calls[1][1] as any).en)).toEqual([]);
});
